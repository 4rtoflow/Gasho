  /** When GashoPlugins made it (its updatedAt, ISO 8601). */
  updatedAt?: string;
  plugins: CatalogPlugin[];
  /** Why the last reading failed; `plugins` are then those read before, if any. */
  error?: string;
  /** Being read now. */
