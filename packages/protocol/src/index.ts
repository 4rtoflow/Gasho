// Data shapes and messages shared by gasho-daemon, gasho-hub and gasho-web.
// This package contains types only, so every import of it must be `import type`.

/** Status reported by `claude agents --json`. */
export type SessionStatus = "busy" | "waiting" | "idle" | "unknown";

/**
 * How the session is reachable from the official apps.
 * - server: spawned by `claude remote-control` (server mode)
 * - interactive: an interactive session with Remote Control enabled
 * - none: a local session without Remote Control
 */
export type RcMode = "server" | "interactive" | "none";

export interface GitHubRepo {
  owner: string;
  name: string;
  url: string;
}

export interface PrLink {
  number: number;
  url: string;
  repository: string;
}

/** A Git repository inside a session's folder, for a folder that is not itself in a repository. */
export interface SessionRepo {
  /** Path from the session's folder, such as "app" or "org/app". */
  path: string;
  branch?: string;
  github?: GitHubRepo;
}

export interface SessionInfo {
  /** Local session id (UUID). */
  sessionId: string;
  pid?: number;
  cwd: string;
  name?: string;
  /** Title generated by Claude Code (`ai-title` in the transcript). */
  title?: string;
  kind?: string;
  status: SessionStatus;
  waitingFor?: string;
  startedAt?: number;
  /** `session_…` id used in https://claude.ai/code/<id>. */
  bridgeSessionId?: string;
  rcMode: RcMode;
  gitBranch?: string;
  github?: GitHubRepo;
  prLinks: PrLink[];
  costUSD?: number;
  lastActivityAt?: number;
  /** Started by Gasho (in zellij), so Gasho can send input to it. */
  managed?: boolean;
  /** Inputs waiting until the session is idle. */
  pendingInputs?: number;
  /** Repositories inside the folder, when the folder is not in a repository but holds some (a workspace of repos). */
  repos?: SessionRepo[];
  /** The model the session uses, as Claude Code names it ("Opus 5.5"); from the transcript. */
  model?: string;
  /** Sessions started from Gasho: the effort level and ultracode as Claude Code shows them above the prompt. */
  effort?: EffortLevel;
  ultracode?: boolean;
  /** Sessions started from Gasho: the tokens used so far, by the session's replies and its subagents'. */
  tokens?: TokenUsage;
  /** …and per hour over the last 48 hours, oldest first: [start of the hour (ms), use]. Hours without use are left out. */
  tokenHours?: [number, TokenUsage][];
}

/** Tokens as Claude Code records them for each reply. */
export interface TokenUsage {
  input: number;
  output: number;
  /** Written to the prompt cache. */
  cacheWrite: number;
  /** Read from the prompt cache (the conversation so far, read again at every turn). */
  cacheRead: number;
}

export type TranscriptBlock =
  | { type: "text"; text: string }
  | { type: "tool_use"; id?: string; name: string; input: string; summary?: string }
  | { type: "tool_result"; toolUseId?: string; content: string; isError: boolean }
  | { type: "image" };

export interface TranscriptEntry {
  uuid: string;
  ts?: string;
  role: "user" | "assistant" | "system";
  blocks: TranscriptBlock[];
  isSidechain?: boolean;
  /** True when the entry is Claude Code's "[Request interrupted by user]" marker. */
  interrupted?: boolean;
}

/** A Claude Code hook event, reduced to what the dashboard shows. */
export interface HookEvent {
  sessionId: string;
  event: string;
  at: number;
  cwd?: string;
  toolName?: string;
  notificationType?: string;
  summary?: string;
}

// In the messages below, `machine` is always a machine id (the id of its registered device), never its name.

export interface MachineHookEvent extends HookEvent {
  machine: string;
}

export type NotificationKind = "done" | "permission" | "idle" | "error";

export interface GashoNotification {
  id: string;
  machine: string;
  sessionId: string;
  at: number;
  kind: NotificationKind;
  title: string;
  body?: string;
  read: boolean;
}

/** A working server: a machine that runs Claude Code and gasho-daemon. */
export interface MachineInfo {
  /** Id issued when the machine was registered. */
  id: string;
  /** Display name; can be changed on the Gasho server. */
  name: string;
  connected: boolean;
  lastSeen: number;
  daemonVersion?: string;
  sessions: SessionInfo[];
  /** Whether Gasho can start sessions on this machine (zellij is available). */
  canLaunch?: boolean;
  /** Folders a session can be started in (already trusted by Claude Code). */
  folders?: string[];
  /** Models as Claude Code's /model picker names them on this machine, once gasho-daemon has seen the picker. */
  models?: ModelOption[];
  /** When gasho-daemon read `models` from the picker (ms since the epoch). */
  modelsAt?: number;
  /**
   * What gasho-daemon can switch or carry with an input to a session started from Gasho. Absent for a gasho-daemon
   * older than 0.6.0, which can switch the model and carry files, but not the effort level or ultracode.
   */
  features?: InputFeature[];
  /** The repositories the kanban watches on this machine (their primary checkouts), as chosen on Gasho. */
  kanbanRepos?: string[];
  /** The repositories that can be chosen for the kanban (gasho-daemon 0.10.0 or later). */
  kanbanOptions?: KanbanRepoOption[];
  /** The kanban of the watched repositories, while gasho-daemon is connected. */
  kanban?: KanbanBoard;
}

// ---- kanban: the worktrees and pull requests of the watched repositories, by whose move it is ----

/** The columns, in their order: my move, the agent works, GitHub works (CI), the reviewers' move, done. */
export type KanbanColumn = "mine" | "agent" | "github" | "review" | "done";

/** Why a card is in its column; Gasho words it, and the next step when the move is mine. */
export type KanbanReason =
  | { kind: "agent_waiting"; waitingFor?: string }
  | { kind: "agent_working" }
  | { kind: "merged"; pr: number }
  | { kind: "closed"; pr: number }
  | { kind: "no_pr" }
  | { kind: "conflict" }
  /** `checks`: up to two of them, as "workflow/job". */
  | { kind: "ci_failed"; checks: string[] }
  | { kind: "changes_requested"; who: string[] }
  | { kind: "ci_running"; checks: string[] }
  | { kind: "draft" }
  | { kind: "rereview"; who: string[] }
  | { kind: "approved" }
  | { kind: "review_waiting" };

/** A Claude Code session working in a card's worktree: any session on the working server, not only Gasho's. */
export interface KanbanSession {
  sessionId: string;
  status: SessionStatus;
  /** Started by Gasho, so the card can open it. */
  managed?: boolean;
}

/** One worktree with its branch's pull request, or an open pull request of mine without a worktree. */
export interface KanbanCard {
  /** Unique on its working server. */
  id: string;
  /** OWNER/REPO */
  repo: string;
  /** The worktree's folder name; "PR #12" for a pull request without a worktree. */
  label: string;
  path?: string;
  branch?: string;
  /** The repository's primary checkout, shown only while it has an open pull request or a session needs it. */
  primary?: boolean;
  /** The pull request's title, or else the branch. */
  title: string;
  /** The issue number in the branch name (feat/12-x → 12). */
  issue?: number;
  /** The open pull request of the branch, or else its latest closed one. */
  pr?: { number: number; url: string; state: "open" | "merged" | "closed"; draft?: boolean };
  /** When the open pull request last changed (ISO 8601). */
  updatedAt?: string;
  column: KanbanColumn;
  reason: KanbanReason;
  sessions: KanbanSession[];
}

/** A repository that can be watched: one in the folders Claude Code trusts on the working server. */
export interface KanbanRepoOption {
  /** Its primary checkout. */
  path: string;
  /** OWNER/REPO on GitHub; absent when its origin is not on GitHub (it cannot be watched). */
  github?: string;
}

/** What gasho-daemon read for the kanban. A repository that could not be read keeps its cards as last read. */
export interface KanbanBoard {
  cards: KanbanCard[];
  errors: { repo: string; error: string }[];
  /** When a repository was last read (ms since the epoch). */
  updatedAt?: number;
  /** Reading the repositories now. */
  checking?: boolean;
}

/** Something registered with the Gasho server: a browser or a working server. */
export type DeviceKind = "browser" | "machine";

export interface DeviceInfo {
  id: string;
  kind: DeviceKind;
  name: string;
  createdAt: number;
  lastSeenAt?: number;
  /** True for the browser making the request. */
  current?: boolean;
}

/** POST /api/pair */
export interface PairRequest {
  code: string;
  kind: DeviceKind;
  name: string;
}

/** Response of POST /api/pair. `token` is returned to machines only; browsers get it as a cookie. */
export interface PairResponse {
  deviceId: string;
  name: string;
  token?: string;
}

/** Response of POST /api/pairing-codes. */
export interface PairingCode {
  code: string;
  expiresAt: number;
}

/** A branch or tag that points at a commit. */
export interface GitRef {
  name: string;
  kind: "local" | "remote" | "tag";
}

export interface GitCommit {
  hash: string;
  parents: string[];
  subject: string;
  author: string;
  /** Commit time, ms since the epoch. */
  at: number;
  refs: GitRef[];
}

export interface GitBranch {
  /** "main" for a local branch, "origin/main" for a remote one. */
  name: string;
  remote: boolean;
  hash: string;
  upstream?: string;
  /** Commits on the branch that its upstream does not have (not pushed yet), and the other way round. */
  ahead?: number;
  behind?: number;
  /** The upstream branch was deleted. */
  upstreamGone?: boolean;
}

/** Branches and recent history of the repository a session works in. */
export interface GitGraph {
  /** Top folder of the repository (or of the worktree). */
  root: string;
  /** Checked-out branch; undefined when HEAD is detached. */
  head?: string;
  headHash?: string;
  branches: GitBranch[];
  /** Newest first, children before their parents. */
  commits: GitCommit[];
  /** More commits exist than were sent. */
  truncated: boolean;
  /** Uncommitted changes in the session's folder. */
  changes?: { staged: number; unstaged: number; untracked: number };
  github?: GitHubRepo;
}

/** Which list of a GitHub repository: its issues or its pull requests. */
export type GitHubListKind = "issues" | "pulls";

/** An open issue or pull request of the GitHub repository a session works in. */
export interface GitHubItem {
  number: number;
  title: string;
  url: string;
  author?: string;
  /** ISO 8601 */
  createdAt: string;
  updatedAt: string;
  labels: { name: string; color?: string }[];
  /** Pull requests: a draft, its branch and the branch it goes into, and the review's state. */
  draft?: boolean;
  head?: string;
  base?: string;
  review?: "approved" | "changes_requested" | "review_required";
}

/** The open issues or pull requests of a repository, newest first, as gasho-daemon read them with `gh`. */
export interface GitHubList {
  repo: GitHubRepo;
  kind: GitHubListKind;
  items: GitHubItem[];
  /** More are open than were sent. */
  truncated: boolean;
}

/** A comment on an issue or pull request. Bodies are GitHub Markdown. */
export interface GitHubComment {
  author?: string;
  /** ISO 8601 */
  createdAt: string;
  body: string;
  url?: string;
  /** Hidden on GitHub (spam, off-topic, …); its body is not sent. */
  minimized?: boolean;
}

/** A review of a pull request. */
export interface GitHubReview {
  author?: string;
  /** ISO 8601 */
  submittedAt: string;
  state: "approved" | "changes_requested" | "commented" | "dismissed" | "pending";
  body: string;
}

/** A check or status of a pull request's latest commit (CI). */
export interface GitHubCheck {
  name: string;
  state: "success" | "failure" | "pending" | "skipped" | "neutral" | "cancelled";
  url?: string;
}

/** A file a pull request changes. */
export interface GitHubFile {
  path: string;
  additions: number;
  deletions: number;
}

/** One issue or pull request with its text and conversation, as gasho-daemon read it with `gh`. */
export interface GitHubItemDetail extends GitHubItem {
  kind: GitHubListKind;
  state: "open" | "closed" | "merged";
  /** Issues closed: whether as done or as not planned. */
  stateReason?: "completed" | "not_planned";
  closedAt?: string;
  mergedAt?: string;
  assignees: string[];
  body: string;
  /** Oldest first; when there are many, the latest ones (`commentsLeftOut` says how many older ones were left out). */
  comments: GitHubComment[];
  commentsLeftOut?: number;
  /** Pull requests only. */
  reviews?: GitHubReview[];
  additions?: number;
  deletions?: number;
  changedFiles?: number;
  files?: GitHubFile[];
  commits?: number;
  checks?: GitHubCheck[];
}

/** A page of transcript entries. `start` is the index of entries[0]; `total` counts all entries. */
export interface TranscriptPage {
  entries: TranscriptEntry[];
  start: number;
  total: number;
  error?: string;
}

