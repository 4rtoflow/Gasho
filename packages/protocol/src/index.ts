/** Models a session started from Gasho can switch to, as Claude Code's /model picker lists them. */
export type SessionModel = "default" | "opus" | "fable" | "sonnet" | "haiku";

/** Claude Code's effort levels, lowest first. */
export type EffortLevel = "low" | "medium" | "high" | "xhigh" | "max";

/** What can be switched with an input, for this session only. */
export type SwitchField = "model" | "effort" | "ultracode";

/** What gasho-daemon can do with an input besides typing it: switch these, and carry files. */
export type InputFeature = SwitchField | "files";

/** A model as Claude Code's /model picker names it on a working server ("Opus 5.5"; for "default", the model it stands for). */
export interface ModelOption {
  id: SessionModel;
  name: string;
}

/** A file sent with an input, base64-encoded. The Gasho server allows 5 files and 10 MB in all per input. */
export interface InputFile {
  name: string;
  data: string;
}

/** Commands a browser can send to a working server, relayed by the Gasho server. */
export type SessionCommand =
  /**
   * `name`: without one, the session is "<folder>-gasho" until its first message, and is then named after it, with the
   * title Claude Code gives the conversation (gasho-daemon 0.10.0 and later; older ones keep "<folder>-gasho").
   * `trust`: when Claude Code asks whether to trust the folder (one it does not trust yet), answer "Yes, I trust this
   * folder" (gasho-daemon 0.10.0 and later). Without it, the launch stops at the question and its result says so
   * (`needsTrust`), so that the person decides.
   */
  | { type: "session.launch"; cwd: string; name?: string; trust?: boolean }
  /** Makes the folder `name` inside the folder `parent` (gasho-daemon 0.10.0 and later). */
  | { type: "folder.create"; parent: string; name: string }
  /**
   * Clones a GitHub repository into the folder `parent` with the working server's GitHub CLI (`gh repo clone`, with its
   * login), as the folder `name` (by default, the repository's name). `repo`: "owner/name", "name" (a repository of the
   * account gh is logged in with), or its URL (gasho-daemon 0.10.0 and later).
   */
  | { type: "repo.clone"; parent: string; repo: string; name?: string }
  /**
   * `model`, `effort`, `ultracode`: switch the session (for this session only) before the text is sent.
   * `files`: saved on the working server and mentioned at the end of the text (`@path`), so Claude reads them.
   */
  | {
      type: "session.input";
      sessionId: string;
      text: string;
      model?: SessionModel;
      effort?: EffortLevel;
      ultracode?: boolean;
      files?: InputFile[];
    }
  | { type: "session.interrupt"; sessionId: string }
  /**
   * Renames a session started from Gasho: in Gasho at once, and in Claude Code with `/rename` (also the name in the
   * official apps), typed like an input once the session is idle.
   */
  | { type: "session.rename"; sessionId: string; name: string }
  /**
   * Starts a copy of a session started from Gasho, with its conversation so far, in the same folder
   * (`claude --resume <id> --fork-session`). The session itself goes on as it was.
   */
  | { type: "session.fork"; sessionId: string; name?: string }
  /**
   * Ends a session started from Gasho (its Claude Code, then its terminal) and removes it from Gasho. Its
   * conversation stays on the working server: `claude --resume` lists it.
   */
  | { type: "session.remove"; sessionId: string }
  /** Answers one of a session's `permissionRequests`. */
  | { type: "permission.answer"; sessionId: string; permissionId: string; decision: PermissionDecision }
  /**
   * Writes a text file inside the session's folder (`path` as in file.get), as UTF-8, up to 1 MB (gasho-daemon 0.11.0
   * and later). `baseHash`: the file's hash when it was read; if the file is no longer that, nothing is written and
   * the result says so (`conflict`). Without it, the file is overwritten. `create`: makes a new file instead, in a
   * folder that is there; nothing that is already there is overwritten.
   */
  | { type: "file.write"; sessionId: string; path: string; content: string; baseHash?: string; create?: boolean };

export interface CommandResult {
  ok: boolean;
  error?: string;
  /**
   * session.launch, session.fork: the new session. session.input: whether the input waits for the session to become
   * idle; session.rename: whether `/rename` does.
   */
  sessionId?: string;
  queued?: boolean;
  /** Sent, but something asked for did not happen (e.g. the model could not be switched). */
  warning?: string;
  /** session.input: what was asked to switch but was not switched (the session keeps what it had). */
  unapplied?: SwitchField[];
  /** folder.create, repo.clone: the folder that was made (an absolute path). */
  path?: string;
  /**
   * session.launch without `trust`: Claude Code asked whether to trust the folder, so nothing was started.
   * `trustWarnings`: what Claude Code pointed out about the folder's own settings while asking (as it wrote it, in
   * English), such as permissions the folder allows in advance.
   */
  needsTrust?: boolean;
  trustWarnings?: string[];
  /** file.write: the file as written. */
  written?: FileStamp;
  /** file.write with `baseHash`: the file changed after it was read (by Claude, or anyone else), so it was not written. */
  conflict?: boolean;
}
