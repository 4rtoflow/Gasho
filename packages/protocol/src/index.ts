// Data shapes and messages shared by gasho-daemon, gasho-hub and gasho-web.
// This package contains types only, so every import of it must be `import type`.

/** Status reported by `claude agents --json`. */
export type SessionStatus = "busy" | "waiting" | "idle" | "unknown";

/**
 * How the session is reachable from the official apps.
 * - server: spawned by `claude remote-control` (server mode)
 * - interactive: an interactive session with Remote Control enabled
 * - none: a local session without Remote Control
 */
export type RcMode = "server" | "interactive" | "none";

export interface GitHubRepo {
  owner: string;
  name: string;
  url: string;
}

export interface PrLink {
  number: number;
  url: string;
  repository: string;
}

/** A Git repository inside a session's folder, for a folder that is not itself in a repository. */
export interface SessionRepo {
  /** Path from the session's folder, such as "app" or "org/app". */
  path: string;
  branch?: string;
  github?: GitHubRepo;
}

export interface SessionInfo {
  /** Local session id (UUID). */
  sessionId: string;
  pid?: number;
  cwd: string;
  name?: string;
  /** Title generated by Claude Code (`ai-title` in the transcript). */
  title?: string;
  kind?: string;
  status: SessionStatus;
  waitingFor?: string;
  startedAt?: number;
  /** `session_…` id used in https://claude.ai/code/<id>. */
  bridgeSessionId?: string;
  rcMode: RcMode;
  gitBranch?: string;
  github?: GitHubRepo;
  prLinks: PrLink[];
  costUSD?: number;
  lastActivityAt?: number;
  /** Started by Gasho (in a terminal of gasho-daemon's), so Gasho can send input to it. */
  managed?: boolean;
  /** Inputs waiting until the session is idle. */
  pendingInputs?: number;
  /** Repositories inside the folder, when the folder is not in a repository but holds some (a workspace of repos). */
  repos?: SessionRepo[];
  /** The model the session uses, as Claude Code names it ("Opus 5.5"); from the transcript. */
  model?: string;
  /** Sessions started from Gasho: the effort level and ultracode as Claude Code shows them above the prompt. */
  effort?: EffortLevel;
  ultracode?: boolean;
  /** Sessions started from Gasho: the tokens used so far, by the session's replies and its subagents'. */
  tokens?: TokenUsage;
  /** …and per hour over the last 48 hours, oldest first: [start of the hour (ms), use]. Hours without use are left out. */
  tokenHours?: [number, TokenUsage][];
  /**
   * Permission requests waiting for an answer, oldest first (Claude Code's PermissionRequest hook). They can be
   * answered from Gasho (`permission.answer`), or in the terminal or the official apps, which removes them here.
   */
  permissionRequests?: PermissionRequestInfo[];
}

/** A permission Claude Code asks for before using a tool. */
export interface PermissionRequestInfo {
  /** Given by gasho-daemon; answers name it. */
  id: string;
  toolName: string;
  /** The tool's input as pretty JSON, clipped. */
  input: string;
  /** Its most telling field (the command, the file, …). */
  summary?: string;
  at: number;
  /**
   * What "allow from now on" would allow, in Claude Code's notation ("Bash(npm test:*)"), when Claude Code suggests
   * a permanent rule for this request; absent when it does not, and "always" cannot be answered.
   */
  always?: string;
  /**
   * AskUserQuestion: the questions Claude asks the person. "allow" answers them with `answers`; without answers,
   * Claude Code would keep its own dialog open. Absent when gasho-daemon cannot pass answers on (before this field).
   */
  questions?: AskedQuestion[];
  /**
   * ExitPlanMode: the plan Claude asks to go ahead with (Markdown, clipped). "allow" approves it (and the session goes
   * on in the `mode` given); "deny" with a `message` sends it back for Claude to plan again. Absent when gasho-daemon
   * cannot approve a plan (before this field).
   */
  plan?: string;
  /**
   * A question that gasho-daemon holds no hook for (it restarted while the question was open, the hook timed out, or
   * it was spent): shown from the transcript, for a session started from Gasho. Answering it closes Claude Code's
   * dialog (Claude is told the person declined it) and sends the answers as the next message.
   */
  answerAsMessage?: boolean;
}

/** One question of an AskUserQuestion. */
export interface AskedQuestion {
  question: string;
  /** A short label for it ("Auth method"). */
  header?: string;
  options: AskedOption[];
  /** More than one option can be chosen. */
  multiSelect?: boolean;
}

export interface AskedOption {
  label: string;
  description?: string;
  /** Something to look at when the option is chosen (a mockup, a code snippet), shown in a monospace box. */
  preview?: string;
}

/**
 * The answer to one question of an AskUserQuestion: the options chosen (indexes into its `options`; at most one when
 * it is not multiSelect) and what the person wrote instead of an option, or besides them.
 */
export interface QuestionAnswer {
  picked: number[];
  text?: string;
}

/** The permission mode a session goes on in once its plan is approved: auto mode, or asking before each edit. */
export type PlanMode = "auto" | "default";

/** allow: this once. always: this time and from now on, as Claude Code suggests. deny: Claude stops and waits. */
export type PermissionDecision = "allow" | "always" | "deny";

/** Tokens as Claude Code records them for each reply. */
export interface TokenUsage {
  input: number;
  output: number;
  /** Written to the prompt cache. */
  cacheWrite: number;
  /** Read from the prompt cache (the conversation so far, read again at every turn). */
  cacheRead: number;
}

export type TranscriptBlock =
  | { type: "text"; text: string }
  | { type: "tool_use"; id?: string; name: string; input: string; summary?: string }
  | { type: "tool_result"; toolUseId?: string; content: string; isError: boolean }
  | { type: "image" };

export interface TranscriptEntry {
  uuid: string;
  ts?: string;
  role: "user" | "assistant" | "system";
  blocks: TranscriptBlock[];
  isSidechain?: boolean;
  /** True when the entry is Claude Code's "[Request interrupted by user]" marker. */
  interrupted?: boolean;
  /**
   * Set on the two system entries of a compaction, when Claude Code summarized the conversation to free its context:
   * "mark" is where it did ("Conversation compacted"), "summary" is the summary the conversation goes on from (Claude
   * Code records it as a user message, which the user did not write). The summary follows its mark.
   */
  compaction?: "mark" | "summary";
}

/** A Claude Code hook event, reduced to what the dashboard shows. */
export interface HookEvent {
  sessionId: string;
  event: string;
  at: number;
  cwd?: string;
  toolName?: string;
  notificationType?: string;
  summary?: string;
}

// In the messages below, `machine` is always a machine id (the id of its registered device), never its name.

export interface MachineHookEvent extends HookEvent {
  machine: string;
}

export type NotificationKind = "done" | "permission" | "idle" | "error";

export interface GashoNotification {
  id: string;
  machine: string;
  sessionId: string;
  at: number;
  kind: NotificationKind;
  title: string;
  body?: string;
  read: boolean;
}

/** A working server: a machine that runs Claude Code and gasho-daemon. */
export interface MachineInfo {
  /** Id issued when the machine was registered. */
  id: string;
  /** Display name; can be changed on the Gasho server. */
  name: string;
  connected: boolean;
  lastSeen: number;
  daemonVersion?: string;
  sessions: SessionInfo[];
  /** Whether Gasho can start sessions on this machine (gasho-daemon can make their terminals). */
  canLaunch?: boolean;
  /** Folders a session can be started in (already trusted by Claude Code). */
  folders?: string[];
  /** Models as Claude Code's /model picker names them on this machine, once gasho-daemon has seen the picker. */
  models?: ModelOption[];
  /** When gasho-daemon read `models` from the picker (ms since the epoch). */
  modelsAt?: number;
  /**
   * What gasho-daemon can switch or carry with an input to a session started from Gasho. Absent for a gasho-daemon
   * older than 0.6.0, which can switch the model and carry files, but not the effort level or ultracode.
   */
  features?: InputFeature[];
}

/** Something registered with the Gasho server: a browser or a working server. */
export type DeviceKind = "browser" | "machine";

export interface DeviceInfo {
  id: string;
  kind: DeviceKind;
  name: string;
  createdAt: number;
  lastSeenAt?: number;
  /** True for the browser making the request. */
  current?: boolean;
}

/** POST /api/pair */
export interface PairRequest {
  code: string;
  kind: DeviceKind;
  name: string;
}

/** Response of POST /api/pair. `token` is returned to machines only; browsers get it as a cookie. */
export interface PairResponse {
  deviceId: string;
  name: string;
  token?: string;
}

/** Response of POST /api/pairing-codes. */
export interface PairingCode {
  code: string;
  expiresAt: number;
}

/** A branch or tag that points at a commit. */
export interface GitRef {
  name: string;
  kind: "local" | "remote" | "tag";
}

export interface GitCommit {
  hash: string;
  parents: string[];
  subject: string;
  author: string;
  /** Commit time, ms since the epoch. */
  at: number;
  refs: GitRef[];
}

export interface GitBranch {
  /** "main" for a local branch, "origin/main" for a remote one. */
  name: string;
  remote: boolean;
  hash: string;
  upstream?: string;
  /** Commits on the branch that its upstream does not have (not pushed yet), and the other way round. */
  ahead?: number;
  behind?: number;
  /** The upstream branch was deleted. */
  upstreamGone?: boolean;
}

/** Branches and recent history of the repository a session works in. */
export interface GitGraph {
  /** Top folder of the repository (or of the worktree). */
  root: string;
  /** Checked-out branch; undefined when HEAD is detached. */
  head?: string;
  headHash?: string;
  branches: GitBranch[];
  /** Newest first, children before their parents. */
  commits: GitCommit[];
  /** More commits exist than were sent. */
  truncated: boolean;
  /** Uncommitted changes in the session's folder. */
  changes?: { staged: number; unstaged: number; untracked: number };
  github?: GitHubRepo;
}

/**
 * Something in a folder inside a session's folder. A symbolic link is what it points to (`link`), and is not opened
 * when it points outside the session's folder (`outside`). "other": anything else, such as a socket or a broken link.
 */
export interface DirEntry {
  name: string;
  kind: "dir" | "file" | "other";
  /** Files: their size in bytes, and when they were last changed (ms since the epoch). */
  size?: number;
  mtime?: number;
  link?: boolean;
  outside?: boolean;
}

/** The entries of a folder inside a session's folder, folders first, then by name. Git's own `.git` is left out. */
export interface DirListing {
  /** From the session's folder, "/"-separated: "" for the folder itself, "src/lib" for one inside it. */
  path: string;
  entries: DirEntry[];
  /** More entries are there than were sent. */
  truncated: boolean;
}

/** A text file as it was just written, to tell whether it changes again. */
export interface FileStamp {
  /** SHA-256 of its bytes, in hex. */
  hash: string;
  size: number;
  /** When it was last changed (ms since the epoch). */
  mtime: number;
}

/**
 * A file inside a session's folder, as gasho-daemon read it: a UTF-8 text file's text (up to 1 MB), or an image's
 * data to show (up to 5 MB). Otherwise neither, with why: the file is binary (or text in another encoding than
 * UTF-8), or too large to send.
 */
export interface FileContent {
  /** As asked for: from the session's folder, "/"-separated. */
  path: string;
  size: number;
  mtime: number;
  /** SHA-256 of the bytes that were read, in hex; saving sends it back, so that changes made meanwhile are not lost. */
  hash?: string;
  /** The text as it is in the file, with its line endings and byte order mark. */
  text?: string;
  image?: { mime: string; data: string };
  binary?: boolean;
  tooLarge?: boolean;
  /** gasho-daemon may write it (the file's permissions). */
  writable: boolean;
}

/** A page of transcript entries. `start` is the index of entries[0]; `total` counts all entries. */
export interface TranscriptPage {
  entries: TranscriptEntry[];
  start: number;
  total: number;
  error?: string;
}

// ---- plugins (docs/plugins.md) ----

/** What a plugin's web part may do besides reading and showing: send messages to sessions. */
export type PluginPermission = "session.input" | "session.launch";

/** A method of a plugin's daemon part, which its web part can call. */
export interface PluginMethodSpec {
  /** read: only reads. write: changes something; the operations log records the call. */
  kind: "read" | "write";
  /** How long to wait for it, in seconds (15 by default, at most 120). */
  timeoutSeconds?: number;
}

/** A setting of a plugin, shown on the settings screen. */
export type PluginSettingSpec = {
  label: string;
  description?: string;
  /** browser: this browser only (its localStorage). server: the same for every browser, kept by the Gasho server. */
  scope: "browser" | "server";
} & (
  | { type: "boolean"; default?: boolean }
  | { type: "number"; default?: number; min?: number; max?: number; step?: number }
  | { type: "string"; default?: string; maxLength?: number }
  | { type: "select"; default?: string; options: { value: string; label: string }[] }
);

/** A plugin's gasho-plugin.json. */
export interface PluginManifest {
  /** 2-32 of a-z, 0-9 and "-", starting with a letter; also the name of its folder. */
  id: string;
  name: string;
  version: string;
  description?: string;
  /** The version of the plugin API it is written for ("1.0"). */
  api: string;
  /** Its files, relative to its folder. */
  web?: { js: string; css?: string };
  daemon?: { js: string };
  methods?: Record<string, PluginMethodSpec>;
  permissions?: PluginPermission[];
  settings?: Record<string, PluginSettingSpec>;
}

/** Where a plugin's daemon part runs: on every working server, or on those listed (machine ids). */
export type PluginMachines = "all" | string[];

/**
 * A plugin's daemon part on one working server. running: it runs. stopped: it is not running (yet, or any more).
 * off: the plugin is disabled, not chosen for this working server, or its gasho-daemon runs no plugins (GASHO_PLUGINS).
 * old: its gasho-daemon is too old for plugins. failed: it failed (`error` says why). offline: the working server is not
 * connected.
 */
export type PluginDaemonState = "running" | "stopped" | "off" | "old" | "failed" | "offline";

/** A plugin installed on the Gasho server, as browsers see it. */
export interface PluginInfo {
  id: string;
  manifest: PluginManifest;
  /** Linked from a folder being developed (hub:plugin add --link). */
  dev: boolean;
  enabled: boolean;
  machines: PluginMachines;
  /** The version in use: the hash of its files. Absent while no version of it can be used. */
  hash?: string;
  /** Where its web part is served (for that version). */
  web?: { js: string; css?: string };
  /** The values of its settings that the Gasho server keeps (scope "server"), defaults included. */
  values: Record<string, unknown>;
  /** Why the plugin, or its newest files, cannot be used. */
  error?: string;
  /** Plugins with a daemon part: its state on each working server, by machine id. */
  daemon?: Record<string, { state: PluginDaemonState; error?: string }>;
}

/** Managing the installed plugins from a browser (answered with plugin.result). */
export type PluginCommand =
  | { type: "plugin.enable"; plugin: string; enabled: boolean }
  | { type: "plugin.machines"; plugin: string; machines: PluginMachines }
  | { type: "plugin.setting"; plugin: string; key: string; value: unknown };

/** A plugin whose daemon part gasho-daemon may have to run, as the Gasho server tells it. */
export interface DaemonPluginEntry {
  id: string;
  /** The version of daemon.js to run (its hash); gasho-daemon asks for the code it does not have (plugin.code.get). */
  hash: string;
  /** Whether to run it on this working server (enabled, and chosen for it). */
  run: boolean;
  /** The values of its settings with scope "server". */
  settings: Record<string, unknown>;
}

/** A plugin's daemon part, as gasho-daemon tells the Gasho server. */
export interface DaemonPluginStatus {
  id: string;
  /** The version that runs. */
  hash?: string;
  state: "running" | "stopped" | "off" | "failed";
  error?: string;
}

